#!/usr/bin/env python3
"""Clean RealSense cup point clouds inside the calibrated table workspace.

中文说明：在校准后的桌面/工作区内采集 RealSense 点云，去除深度边缘飞点、
桌面平面、近桌面残留和离群点，并对杯子候选 cluster 保存 raw/clean PLY。
该脚本只做感知和调试输出，不移动机器人。

This script is perception-only and does not move the Kinova arm.

Pipeline:
1. Capture one aligned RealSense RGB-D frame.
2. Detect ArUco marker ID 23 and compute T_base_camera.
3. Remove depth-edge pixels before point-cloud generation.
4. Build a base-frame point cloud.
5. Crop by configs/table_workspace.yaml.
6. Remove the table plane.
7. DBSCAN cluster remaining objects.
8. Clean each cluster with statistical and radius outlier removal.
9. Save raw/cleaned debug point clouds for inspection.
"""

